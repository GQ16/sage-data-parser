    private static Invoice openInvoice(int seq, String customerId, LocalDate date, Customer customer) {
        Invoice inv = new Invoice();
        inv.invoiceId        = startId + seq;
        inv.sourceCustomerId = customerId;
        inv.invoiceDate      = date;
        inv.customer         = customer;
        return inv;
    }

    private static Customer buildCustomerFromRow(String[] row, ColumnMap cm) {
        Customer c = new Customer();
        c.customerId    = safeGet(row, cm.customerId);
        c.name          = safeGet(row, cm.name);
        c.billToContact = safeGet(row, cm.billToContact);
        c.phone         = normalizePhone(safeGet(row, cm.phone));
        return c;
    }

    private static String normalizePhone(String raw) {
        if (raw == null) return null;
        String digits = raw.replaceAll("\\D", "");
        if (digits.isEmpty()) return null;
        if (digits.length() == 11 && digits.startsWith("1")) digits = digits.substring(1);
        return digits;
    }

    /**
     * Updates (or creates) a Vehicle from a legacy comment row.
     * Handles:
     *   • VIN lines     – "VIN: 3MZBM1L70FM217353"
     *   • Mileage lines – "2015 MAZDA 3 MILES: 117,308"
     */
    private static Vehicle buildOrUpdateVehicle(Vehicle existing, String[] row, ColumnMap cm) {
        String desc = safeGet(row, cm.itemDesc);
        if (isBlank(desc)) return existing;

        String upper = desc.toUpperCase(Locale.ROOT);
        boolean isVin     = upper.startsWith("VIN") || upper.contains("VIN:") || upper.startsWith("VIN#");
        boolean isMileage = upper.contains("MILEAGE") || upper.contains("MILES:");

        if (!isVin && !isMileage) return existing;
        if (existing == null) existing = new Vehicle();

        if (isVin) {
            String vin = desc.replace("VIN#","").replace("VIN:","").replace("VIN","")
                    .replace("vin#","").replace("vin:","").replace("vin","")
                    .replace(":"," ").trim().replaceAll("\\s+","");
            if (!isBlank(vin) && isBlank(existing.vin)) existing.vin = vin;
            return existing;
        }

        // Mileage line: "2015 MAZDA 3 MILES: 117,308"
        String text   = desc.trim();
        String upper2 = text.toUpperCase(Locale.ROOT);
        int mileIdx   = upper2.indexOf("MILE");
        int cutIdx    = mileIdx >= 0 ? mileIdx : text.length();
        String left   = text.substring(0, cutIdx).trim();
        String right  = text.substring(cutIdx).trim();

        String[] tokens = left.split("\\s+");
        int year = 0, yearIdx = -1;
        for (int k = 0; k < tokens.length; k++) {
            String d = tokens[k].replaceAll("[^0-9]","");
            if (d.length() == 4 && d.matches("\\d{4}")) {
                year = Integer.parseInt(d); yearIdx = k; break;
            }
        }

        String make = null, model = null;
        if (yearIdx >= 0 && yearIdx + 1 < tokens.length) {
            StringBuilder mm = new StringBuilder();
            for (int j = yearIdx + 1; j < tokens.length; j++) {
                if (mm.length() > 0) mm.append(' ');
                mm.append(tokens[j].replaceAll(",",""));
            }
            String mmStr = mm.toString().trim();
            if (!mmStr.isEmpty()) {
                String[] parts = mmStr.split("\\s+", 2);
                make = parts[0];
                if (parts.length > 1) model = parts[1];
            }
        }

        if (year != 0) existing.year = year;
        if (make  != null) existing.make  = make;
        if (model != null) existing.model = model;

        String milesDigits = right.replaceAll("[^0-9]","");
        if (!milesDigits.isEmpty()) {
            try { existing.mileage = Integer.parseInt(milesDigits); }
            catch (NumberFormatException ignored) {}
        }

        if (existing.description == null && year != 0 && make != null) existing.description = text;
        return existing;
    }

    private static InvoiceLine buildLineFromRow(String[] row, ColumnMap cm) {
        InvoiceLine line = new InvoiceLine();
        line.itemId             = safeGet(row, cm.itemId);
        line.itemDescription    = safeGet(row, cm.itemDesc);
        line.stockingUm         = safeGet(row, cm.stockingUm);
        line.qty                = parseBigDecimal(safeGet(row, cm.qty));
        line.amount             = parseBigDecimal(safeGet(row, cm.amount));
        line.costOfSales        = parseBigDecimal(safeGet(row, cm.costOfSales));
        line.grossProfit        = parseBigDecimal(safeGet(row, cm.grossProfit));
        line.grossMarginPercent = parseBigDecimal(safeGet(row, cm.grossMargin));
        line.serialNumber       = safeGet(row, cm.serialNumber);
        line.serialNumberStatus = safeGet(row, cm.serialStatus);
        line.itemType           = safeGet(row, cm.itemType);
        line.itemCategory       = safeGet(row, cm.itemCategory);
        line.isCommentOnly      = (line.qty == null || BigDecimal.ZERO.compareTo(line.qty) == 0)
                && line.amount == null && !isBlank(line.itemDescription);
        return line;
    }

    private static void applySummaryToInvoice(Invoice invoice, String[] row, ColumnMap cm) {
        invoice.totalQty                = parseBigDecimal(safeGet(row, cm.qty));
        invoice.totalAmount             = parseBigDecimal(safeGet(row, cm.amount));
        invoice.totalCostOfSales        = parseBigDecimal(safeGet(row, cm.costOfSales));
        invoice.totalGrossProfit        = parseBigDecimal(safeGet(row, cm.grossProfit));
        invoice.totalGrossMarginPercent = parseBigDecimal(safeGet(row, cm.grossMargin));
    }

    // =========================================================================
    // Builders  (NEW SAGE)
    // =========================================================================

    private static Customer buildCustomerFromRowNew(String[] row, ColumnMap cm) {
        Customer c = new Customer();
        c.customerId = safeGet(row, cm.customerId);
        // Prefer "Ship to Name" as the display name; fall back to Customer ID
        String shipName = safeGet(row, cm.shipToName);
        c.name          = !isBlank(shipName) ? shipName : c.customerId;
        c.phone         = null;   // not available in this export
        c.billToContact = null;
        return c;
    }

    private static InvoiceLine buildLineFromRowNew(String[] row, ColumnMap cm) {
        InvoiceLine line = new InvoiceLine();
        line.itemId          = safeGet(row, cm.itemId);
        line.itemDescription = safeGet(row, cm.itemDesc);
        line.stockingUm      = safeGet(row, cm.stockingUm);
        line.qty             = parseBigDecimal(safeGet(row, cm.qty));
        line.serialNumber    = safeGet(row, cm.serialNumber);

        // Amounts in this Sage export are negative AR entries; negate to get the sale value.
        BigDecimal raw = parseBigDecimal(safeGet(row, cm.amount));
        line.amount = (raw != null) ? raw.negate() : null;

        // Cost-of-sales / GP not available in this format
        line.costOfSales        = null;
        line.grossProfit        = null;
        line.grossMarginPercent = null;
        line.serialNumberStatus = null;
        line.itemType           = null;
        line.itemCategory       = null;

        line.isCommentOnly = (line.qty == null || BigDecimal.ZERO.compareTo(line.qty) == 0)
                && line.amount == null && !isBlank(line.itemDescription);
        return line;
    }

    /**
     * Parse a Vehicle from free-text (Invoice Note or zero-amount comment lines).
     *
     * Handles patterns like:
     *   "2003 CHEVY FULL CONVERSION VAN"
     *   "DISCOVER 1998 TOYOTA AVALON"         payment prefix before year
     *   "2001 TOYOTA SONOTA VISA DEBIT"        payment suffix after model
     *   "1988 TOYOTA PICK UP 4x4"
     *
     * Returns null when no vehicle year can be found.
     */
    private static Vehicle parseVehicleFromNote(String text) {
        if (isBlank(text)) return null;

        Set<String> paymentWords = new HashSet<>(Arrays.asList(
                "DISCOVER","VISA","MASTERCARD","AMEX","CASH","CHECK","DEBIT","CREDIT","MC","DINERS"
        ));

        String upper  = text.toUpperCase(Locale.ROOT).trim();
        String[] toks = upper.split("\\s+");

        // Find first token that looks like a vehicle year (1960-2035)
        int yearIndex = -1, year = 0;
        for (int i = 0; i < toks.length; i++) {
            String d = toks[i].replaceAll("[^0-9]","");
            if (d.length() == 4) {
                try {
                    int y = Integer.parseInt(d);
                    if (y >= 1960 && y <= 2035) { year = y; yearIndex = i; break; }
                } catch (NumberFormatException ignored) {}
            }
        }
        if (year == 0 || yearIndex + 1 >= toks.length) return null;

        // Collect tokens after the year, stopping at the first payment keyword
        List<String> rest = new ArrayList<>();
        for (int i = yearIndex + 1; i < toks.length; i++) {
            if (paymentWords.contains(toks[i])) break;
            rest.add(toks[i]);
        }
        if (rest.isEmpty()) return null;

        Vehicle v = new Vehicle();
        v.year  = year;
        v.make  = rest.get(0);
        if (rest.size() > 1) v.model = String.join(" ", rest.subList(1, rest.size()));
        v.description = year + " " + v.make + (v.model != null ? " " + v.model : "");
        return v;
    }

    /** Merge newV into existing, only filling in fields that are absent in existing. */
    private static Vehicle mergeVehicle(Vehicle existing, Vehicle newV) {
        if (existing == null) return newV;
        if (newV     == null) return existing;
        if (existing.year == 0    && newV.year  != 0)    existing.year  = newV.year;
        if (isBlank(existing.make)  && !isBlank(newV.make))  existing.make  = newV.make;
        if (isBlank(existing.model) && !isBlank(newV.model)) existing.model = newV.model;
        if (isBlank(existing.vin)   && !isBlank(newV.vin))   existing.vin   = newV.vin;
        if (existing.mileage == 0  && newV.mileage != 0)  existing.mileage = newV.mileage;
        if (isBlank(existing.description) && !isBlank(newV.description))
            existing.description = newV.description;
        return existing;
    }

    /**
     * Compute totalAmount and totalQty from line items.
     * Used by the New Sage format which has no dedicated summary row.
     * Amounts have already been negated to positive sale values at this point.
     */
    private static void computeTotalsFromLines(Invoice inv) {
        BigDecimal sumAmt = BigDecimal.ZERO;
        BigDecimal sumQty = BigDecimal.ZERO;
        for (InvoiceLine l : inv.lines) {
            if (l.amount != null) sumAmt = sumAmt.add(l.amount);
            if (l.qty    != null) sumQty = sumQty.add(l.qty);
        }
        inv.totalAmount = sumAmt;
        inv.totalQty    = sumQty;
    }

    /** Null out vehicles that lack year+make+model, and trim notes whitespace. */
    private static void finalizeInvoice(Invoice inv) {
        if (!hasMinimalVehicle(inv.vehicle)) inv.vehicle = null;
        if (inv.notes != null) {
            inv.notes = inv.notes.trim();
            if (inv.notes.isEmpty()) inv.notes = null;
        }
    }

    private static boolean hasLegitimateInvoiceLines(Invoice inv) {
        if (inv == null || inv.lines == null || inv.lines.isEmpty()) return false;
        for (InvoiceLine line : inv.lines) {
            if (line == null) continue;
            if (!isBlank(line.itemId) || !isBlank(line.itemDescription)) return true;
        }
        return false;
    }

    // =========================================================================
    // Utility methods
    // =========================================================================

    private static String safeGet(String[] row, int idx) {
        if (row == null || idx < 0 || idx >= row.length) return "";
        String v = row[idx];
        return v == null ? "" : v.trim();
    }

    private static boolean isBlank(String s) {
        return s == null || s.trim().isEmpty();
    }

    private static boolean isNumeric(String s) {
        if (isBlank(s)) return false;
        try { new BigDecimal(s.replace(",","")); return true; }
        catch (NumberFormatException e) { return false; }
    }

    private static BigDecimal parseBigDecimal(String s) {
        if (isBlank(s)) return null;
        try { return new BigDecimal(s.replace(",","")); }
        catch (NumberFormatException e) { return null; }
    }

    private static LocalDate parseDate(String s) {
        if (isBlank(s)) return null;
        s = s.trim();
        try { return LocalDate.parse(s, DATE_FMT);    } catch (Exception ignored) {}
        try { return LocalDate.parse(s, DATE_FMT_4Y); } catch (Exception ignored) {}
        return null;
    }

    private static int parseIntSafe(String s) {
        if (isBlank(s)) return -1;
        try { return Integer.parseInt(s.trim()); }
        catch (NumberFormatException e) { return -1; }
    }

    private static boolean hasMinimalVehicle(Vehicle v) {
        if (v == null) return false;
        return v.year != 0 && !isBlank(v.make) && !isBlank(v.model);
    }
