    // =========================================================================
    // CSV format detection + column mapping
    // =========================================================================

    private enum CsvFormat { LEGACY, NEW_SAGE }

    /**
     * Dynamic column-index map built from the first (header) row of the CSV.
     * Every field defaults to -1 (not present); safeGet() handles that gracefully.
     */
    private static class ColumnMap {
        CsvFormat format;

        // ---- Common ----
        int customerId   = -1;
        int date         = -1;
        int itemId       = -1;
        int qty          = -1;
        int amount       = -1;
        int itemDesc     = -1;
        int serialNumber = -1;
        int stockingUm   = -1;

        // ---- LEGACY-only ----
        int name          = -1;
        int billToContact = -1;
        int phone         = -1;
        int costOfSales   = -1;
        int grossProfit   = -1;
        int grossMargin   = -1;
        int serialStatus  = -1;
        int itemType      = -1;
        int itemCategory  = -1;

        // ---- NEW_SAGE-only ----
        int invoiceCmNum = -1;   // "Invoice/CM #"
        int shipToName   = -1;   // "Ship to Name"
        int invoiceNote  = -1;   // "Invoice Note"
        int invoiceDist  = -1;   // "Invoice/CM Distribution"  (0 = tax header; ≥1 = lines)
        int creditMemo   = -1;   // "Credit Memo"
        int unitPrice    = -1;   // "Unit Price"
    }

    private static ColumnMap buildColumnMap(String[] header) {
        ColumnMap cm = new ColumnMap();
        for (int i = 0; i < header.length; i++) {
            switch (header[i].trim().toLowerCase(Locale.ROOT)) {
                case "customer id"             -> cm.customerId    = i;
                case "name"                    -> cm.name          = i;
                case "item id"                 -> cm.itemId        = i;
                case "bill to contact"         -> cm.billToContact = i;
                case "last inv date"           -> cm.date          = i;
                case "date"                    -> { if (cm.date        == -1) cm.date        = i; }
                case "telephone 1"             -> cm.phone         = i;
                case "qty"                     -> cm.qty           = i;
                case "quantity"                -> { if (cm.qty         == -1) cm.qty         = i; }
                case "stocking u/m"            -> cm.stockingUm    = i;
                case "u/m id"                  -> { if (cm.stockingUm  == -1) cm.stockingUm  = i; }
                case "amount"                  -> cm.amount        = i;
                case "cost of sales"           -> cm.costOfSales   = i;
                case "gross profit"            -> cm.grossProfit   = i;
                case "gross margin"            -> cm.grossMargin   = i;
                case "item description"        -> cm.itemDesc      = i;
                case "description"             -> { if (cm.itemDesc    == -1) cm.itemDesc    = i; }
                case "serial number"           -> cm.serialNumber  = i;
                case "serial number status"    -> cm.serialStatus  = i;
                case "item class"              -> cm.itemType      = i;
                case "description for sales"   -> cm.itemCategory  = i;
                // New Sage
                case "invoice/cm #"            -> cm.invoiceCmNum  = i;
                case "ship to name"            -> cm.shipToName    = i;
                case "invoice note"            -> cm.invoiceNote   = i;
                case "invoice/cm distribution" -> cm.invoiceDist   = i;
                case "credit memo"             -> cm.creditMemo    = i;
                case "unit price"              -> cm.unitPrice     = i;
            }
        }
        cm.format = (cm.invoiceCmNum >= 0) ? CsvFormat.NEW_SAGE : CsvFormat.LEGACY;
        return cm;
    }

