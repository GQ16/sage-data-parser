    /**
     * args[0] = output JSON path
     * args[1] = CSV classpath resource (optional, default /NewSales.CSV)
     */
    public static void main(String[] args) throws IOException, CsvException {
        if (args.length < 1) {
            System.err.println("Usage: java SalesToInvoiceJson <outputJsonPath> [<csvResourcePath>]");
            System.exit(1);
        }

        String outputJson   = args[0];
        String resourcePath = args.length >= 2 ? args[1] : "/NewSales.CSV";

        InputStream csvStream = SalesToInvoiceJson.class.getResourceAsStream(resourcePath);
        if (csvStream == null) {
            throw new IllegalStateException("Could not find CSV on classpath at: " + resourcePath);
        }

        Root root = convertCsvToInvoices(csvStream);

        ObjectMapper mapper = new ObjectMapper()
                .enable(SerializationFeature.INDENT_OUTPUT)
                .findAndRegisterModules();                        // registers JavaTimeModule
        mapper.configure(SerializationFeature.WRITE_DATES_AS_TIMESTAMPS, false);

        mapper.writeValue(Paths.get(outputJson).toFile(), root);
        System.out.printf("Written %d invoices to %s%n", root.invoices.size(), outputJson);
    }

    // =========================================================================
    // Public API
    // =========================================================================

    public static Root convertCsvToInvoices(InputStream csvStream) throws IOException, CsvException {
        Root root = new Root();

        // Buffer the entire stream so we can detect format from the header first,
        // then re-read with the appropriate CSV parser settings.
        byte[] csvBytes = csvStream.readAllBytes();

        // ── Step 1: read header row only (default parser is fine for headers) ──
        ColumnMap cm;
        try (CSVReader headerReader = new CSVReader(
                new InputStreamReader(new ByteArrayInputStream(csvBytes), StandardCharsets.UTF_8))) {
            String[] header = headerReader.readNext();
            if (header == null) return root;
            cm = buildColumnMap(header);
        }

        // ── Step 2: re-parse the full CSV with a format-appropriate parser ──────
        //
        // NEW_SAGE: historic Sage exports contain malformed quoted fields
        //   (e.g. `"16" PACER 164P"`) that cause strict RFC-4180 parsers to
        //   throw "Unterminated quoted field".  Using withIgnoreQuotations(true)
        //   treats quote characters as literal text, which is safe because the
        //   NEW_SAGE format does not use quoted fields to embed commas.
        //
        // LEGACY: must use proper quoting because description / mileage fields
        //   legitimately embed commas (e.g. `"2003 Honda CR-V MILEAGE: 194,275"`).
        CSVParser csvParser = new CSVParserBuilder()
                .withIgnoreQuotations(cm.format == CsvFormat.NEW_SAGE)
                .build();

        try (CSVReader reader = new CSVReaderBuilder(
                new InputStreamReader(new ByteArrayInputStream(csvBytes), StandardCharsets.UTF_8))
                .withCSVParser(csvParser)
                .build()) {

            List<String[]> rows = reader.readAll();
            if (rows.isEmpty()) return root;

            if (cm.format == CsvFormat.NEW_SAGE) {
                convertNewSage(rows, cm, root);
            } else {
                convertLegacy(rows, cm, root);
            }
        }
        return root;
    }

    // =========================================================================
    // LEGACY format  (Sales.csv)
    // =========================================================================

    private static void convertLegacy(List<String[]> rows, ColumnMap cm, Root root) {
        Invoice currentInvoice = null;
        int invoiceSeq = 1;

        for (int i = 1; i < rows.size(); i++) {
            String[] row = rows.get(i);
            if (isRowEmpty(row)) continue;

            // Summary row: close the current invoice with totals
            if (isSummaryRow(row, cm)) {
                if (currentInvoice != null) {
                    applySummaryToInvoice(currentInvoice, row, cm);
                    finalizeInvoice(currentInvoice);
                    root.invoices.add(currentInvoice);
                    currentInvoice = null;
                }
                continue;
            }

            String rowCustomerId   = safeGet(row, cm.customerId);
            String rowCustomerName = safeGet(row, cm.name);
            LocalDate rowDate      = parseDate(safeGet(row, cm.date));
            boolean hasCustomer    = !isBlank(rowCustomerId) || !isBlank(rowCustomerName);

            if (currentInvoice == null) {
                if (!hasCustomer) continue;
                currentInvoice = openInvoice(invoiceSeq++, rowCustomerId, rowDate,
                        buildCustomerFromRow(row, cm));
            } else {
                String curId   = currentInvoice.customer.customerId == null ? "" : currentInvoice.customer.customerId;
                String curName = currentInvoice.customer.name       == null ? "" : currentInvoice.customer.name;
                boolean sameCustomer =
                        curId.equalsIgnoreCase(rowCustomerId) &&
                        curName.equalsIgnoreCase(rowCustomerName);
                boolean sameDate =
                        (currentInvoice.invoiceDate == null && rowDate == null) ||
                        (currentInvoice.invoiceDate != null && currentInvoice.invoiceDate.equals(rowDate));

                if (hasCustomer && !(sameCustomer && sameDate)) {
                    // Different customer or date -> close current, start fresh
                    finalizeInvoice(currentInvoice);
                    root.invoices.add(currentInvoice);
                    currentInvoice = openInvoice(invoiceSeq++, rowCustomerId, rowDate,
                            buildCustomerFromRow(row, cm));
                } else if (hasCustomer && sameCustomer && currentInvoice.invoiceDate == null && rowDate != null) {
                    currentInvoice.invoiceDate = rowDate;
                }
            }

            if (isVehicleCommentRow(row, cm)) {
                currentInvoice.vehicle = buildOrUpdateVehicle(currentInvoice.vehicle, row, cm);
            } else if (isLineItemRow(row, cm)) {
                InvoiceLine line = buildLineFromRow(row, cm);
                line.sortOrder = currentInvoice.lines.size();
                currentInvoice.lines.add(line);
            } else {
                String desc = safeGet(row, cm.itemDesc);
                if (!isBlank(desc)) {
                    if (currentInvoice.notes == null) currentInvoice.notes = "";
                    currentInvoice.notes += desc.trim() + '\n';
                }
            }
        }

        if (currentInvoice != null) {
            finalizeInvoice(currentInvoice);
            root.invoices.add(currentInvoice);
        }
    }

    // =========================================================================
    // NEW SAGE format  (NewSales.CSV)
    // =========================================================================

    /**
     * Each Sage invoice maps to one or more CSV rows sharing the same Customer ID +
     * Invoice/CM #.  Distribution 0 is a tax-header row (skipped as a line item).
     * Distributions >= 1 are the actual product/service lines.
     *
     * Amounts in this export are stored as negative AR entries; we negate them to
     * produce positive sale values.  Credit memos (Credit Memo = TRUE) are skipped.
     */
    private static void convertNewSage(List<String[]> rows, ColumnMap cm, Root root) {
        Invoice currentInvoice = null;
        String  currentKey     = null;
        int     invoiceSeq     = 1;

        for (int i = 1; i < rows.size(); i++) {
            String[] row = rows.get(i);
            if (isRowEmpty(row)) continue;

            String customerId = safeGet(row, cm.customerId);
            String invoiceNum = safeGet(row, cm.invoiceCmNum);
            if (isBlank(invoiceNum)) continue;

            String invoiceKey = customerId + "|" + invoiceNum;

            // ---- Open / close invoice on key change --------------------------------
            if (!invoiceKey.equals(currentKey)) {
                if (currentInvoice != null) {
                    computeTotalsFromLines(currentInvoice);
                    finalizeInvoice(currentInvoice);
                    if (hasLegitimateInvoiceLines(currentInvoice)) {
                        root.invoices.add(currentInvoice);
                    }
                }
                currentKey = invoiceKey;

                // Credit memos are not imported into the new system
                String creditMemo = safeGet(row, cm.creditMemo);
                if ("TRUE".equalsIgnoreCase(creditMemo)) {
                    currentInvoice = null;
                    continue;
                }

                currentInvoice = openInvoice(invoiceSeq++, customerId,
                        parseDate(safeGet(row, cm.date)), buildCustomerFromRowNew(row, cm));
                currentInvoice.sourceInvoiceNumber = invoiceNum;

                // Extract vehicle from Invoice Note on the first row of this invoice
                String note = safeGet(row, cm.invoiceNote);
                if (!isBlank(note)) {
                    Vehicle v = parseVehicleFromNote(note);
                    if (v != null) {
                        currentInvoice.vehicle = v;
                    } else {
                        currentInvoice.notes = note.trim() + "\n";
                    }
                }
            }

            if (currentInvoice == null) continue;  // skipping credit memo rows

            // Update customer display name when Ship to Name becomes available
            if (cm.shipToName >= 0) {
                String shipName = safeGet(row, cm.shipToName);
                if (!isBlank(shipName) && isBlank(currentInvoice.customer.name)) {
                    currentInvoice.customer.name = shipName;
                }
            }

            // ---- Distribution routing -----------------------------------------------
            int dist = parseIntSafe(safeGet(row, cm.invoiceDist));

            if (dist == 0) {
                // Distribution 0 = invoice-level tax header row.
                // Re-check Invoice Note in case it was blank when the invoice was opened.
                if (currentInvoice.vehicle == null) {
                    String note = safeGet(row, cm.invoiceNote);
                    if (!isBlank(note)) {
                        Vehicle v = parseVehicleFromNote(note);
                        if (v != null) currentInvoice.vehicle = v;
                    }
                }
                continue;
            }

            // dist >= 1: actual distribution line
            String itemId = safeGet(row, cm.itemId);
            String desc   = safeGet(row, cm.itemDesc);
            BigDecimal qty    = parseBigDecimal(safeGet(row, cm.qty));
            BigDecimal amount = parseBigDecimal(safeGet(row, cm.amount));

            // Ignore malformed data rows that have neither an Item ID nor a description.
            if (isBlank(itemId) && isBlank(desc)) continue;

            boolean zeroQty = qty    == null || BigDecimal.ZERO.compareTo(qty)    == 0;
            boolean zeroAmt = amount == null || BigDecimal.ZERO.compareTo(amount) == 0;

            // Zero-qty + zero-amount + no Item ID -> vehicle / note comment line
            if (isBlank(itemId) && zeroQty && zeroAmt) {
                if (!isBlank(desc)) {
                    Vehicle v = parseVehicleFromNote(desc);
                    if (v != null) {
                        currentInvoice.vehicle = mergeVehicle(currentInvoice.vehicle, v);
                    } else {
                        if (currentInvoice.notes == null) currentInvoice.notes = "";
                        currentInvoice.notes += desc.trim() + "\n";
                    }
                }
                continue;
            }

            // Real product / service line
            InvoiceLine line = buildLineFromRowNew(row, cm);
            line.sortOrder = currentInvoice.lines.size();
            currentInvoice.lines.add(line);
        }

        // Finalize the last open invoice
        if (currentInvoice != null) {
            computeTotalsFromLines(currentInvoice);
            finalizeInvoice(currentInvoice);
            if (hasLegitimateInvoiceLines(currentInvoice)) {
                root.invoices.add(currentInvoice);
            }
        }
    }

    // =========================================================================
    // Row-classification helpers  (LEGACY)
    // =========================================================================

    private static boolean isRowEmpty(String[] row) {
        for (String s : row) { if (!isBlank(s)) return false; }
        return true;
    }

    private static boolean isSummaryRow(String[] row, ColumnMap cm) {
        if (!isBlank(safeGet(row, cm.customerId))) return false;
        if (!isBlank(safeGet(row, cm.name)))       return false;
        if (!isBlank(safeGet(row, cm.itemId)))     return false;
        boolean hasNumeric = isNumeric(safeGet(row, cm.qty))
                || isNumeric(safeGet(row, cm.amount))
                || isNumeric(safeGet(row, cm.costOfSales));
        return hasNumeric && isBlank(safeGet(row, cm.itemDesc));
    }

    private static boolean isVehicleCommentRow(String[] row, ColumnMap cm) {
        String desc = safeGet(row, cm.itemDesc);
        if (isBlank(desc)) return false;
        if (!isBlank(safeGet(row, cm.itemId))) return false;
        boolean hasFinancials =
                isNumeric(safeGet(row, cm.qty))       || isNumeric(safeGet(row, cm.amount))
                || isNumeric(safeGet(row, cm.costOfSales)) || isNumeric(safeGet(row, cm.grossProfit))
                || isNumeric(safeGet(row, cm.grossMargin));
        if (hasFinancials) return false;
        String upper = desc.toUpperCase(Locale.ROOT);
        return upper.contains("MILEAGE")
                || upper.startsWith("VIN")
                || upper.contains("VIN:")
                || upper.matches(".*\\b(TOYOTA|HONDA|NISSAN|FORD|CHEVY|CHEVROLET|GMC|JEEP|DODGE"
                        + "|LEXUS|KIA|HYUNDAI|SUBARU|MERCEDES|BUICK|MAZDA|MASERATI"
                        + "|PONTIAC|CADILLAC|CHRYSLER|LINCOLN|ACURA|INFINITI|MITSUBISHI"
                        + "|VOLKSWAGEN|VW|BMW|AUDI|VOLVO|SUZUKI|HUMMER|MINI)\\b.*");
    }

    private static boolean isLineItemRow(String[] row, ColumnMap cm) {
        if (!isBlank(safeGet(row, cm.itemId))) return true;
        return isNumeric(safeGet(row, cm.qty)) || isNumeric(safeGet(row, cm.amount));
    }

    // =========================================================================
    // Builders  (shared + LEGACY)
